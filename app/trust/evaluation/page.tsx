import { PageHeader, Section } from "@/components/page";
import { TrustTabs } from "@/components/trust-tabs";
import { checkLabel } from "@/lib/checks/labels";
import { percent } from "@/lib/format";
import report from "@/eval/report.json";

export const metadata = { title: "Evaluation" };

interface Metrics {
  tp: number;
  fp: number;
  fn: number;
  tn: number;
  precision: number | null;
  recall: number | null;
}

interface SeedResult {
  seed: string;
  invoices: number;
  labelledInvoices: number;
  checks: Record<string, Metrics>;
}

interface AgentBlock {
  promptVersion: string;
  runs: number;
  passRate: number | null;
  schemaPassRate: number | null;
  citationValidity: number | null;
  amountFaithfulness: number | null;
  retryRate: number | null;
  errorRate: number | null;
  avgTokens: number | null;
  avgLatencyMs: number | null;
}

const r = report as unknown as {
  demoToday: string;
  configVersion: string;
  limits: string[];
  checks: { dev: SeedResult; holdout: SeedResult };
  agent?: AgentBlock | null;
  gate: { passed: boolean };
};

export default function EvaluationPage() {
  const seeds = [r.checks.dev, r.checks.holdout];
  const ids = Object.keys(r.checks.dev.checks);
  return (
    <>
      <PageHeader
        title="Trust Panel"
        description="How the checks and the agent perform against a labelled synthetic test set. Generated by scripts/eval.ts and checked in CI."
      />
      <TrustTabs current="/trust/evaluation" />

      <Section
        title="Checks"
        description={`Config ${r.configVersion}. Precision: of the invoices a check flagged, how many it should have. Recall: of the invoices it should have flagged, how many it did.`}
      >
        <div className="bg-card overflow-x-auto rounded-md border">
          <table className="w-full text-sm">
            <caption className="sr-only">
              Precision and recall per check on the development and holdout
              datasets
            </caption>
            <thead className="text-muted-foreground border-b">
              <tr>
                <th scope="col" className="px-3 py-2 text-left font-medium">
                  Check
                </th>
                {seeds.map((s) => (
                  <th
                    key={s.seed}
                    scope="col"
                    colSpan={3}
                    className="px-3 py-2 text-right font-medium capitalize"
                  >
                    {s.seed === "dev" ? "Development set" : "Holdout set"} (
                    {s.invoices} invoices)
                  </th>
                ))}
              </tr>
              <tr className="text-xs">
                <th scope="col" />
                {seeds.flatMap((s) => [
                  <th
                    key={`${s.seed}-p`}
                    scope="col"
                    className="px-3 py-1 text-right font-normal"
                  >
                    Precision
                  </th>,
                  <th
                    key={`${s.seed}-r`}
                    scope="col"
                    className="px-3 py-1 text-right font-normal"
                  >
                    Recall
                  </th>,
                  <th
                    key={`${s.seed}-n`}
                    scope="col"
                    className="px-3 py-1 text-right font-normal"
                  >
                    Positives
                  </th>,
                ])}
              </tr>
            </thead>
            <tbody className="divide-y">
              {ids.map((id) => (
                <tr key={id}>
                  <th scope="row" className="px-3 py-2 text-left font-normal">
                    {checkLabel(id)}
                  </th>
                  {seeds.flatMap((s) => {
                    const m = s.checks[id]!;
                    return [
                      <td
                        key={`${s.seed}-p`}
                        className="num px-3 py-2 text-right"
                      >
                        {percent(m.precision)}
                      </td>,
                      <td
                        key={`${s.seed}-r`}
                        className="num px-3 py-2 text-right"
                      >
                        {percent(m.recall)}
                      </td>,
                      <td
                        key={`${s.seed}-n`}
                        className="num text-muted-foreground px-3 py-2 text-right"
                      >
                        {m.tp + m.fn}
                      </td>,
                    ];
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Section>

      <Section
        title="Agent"
        description="From the stored precompute runs. CI never calls the model."
      >
        {r.agent ? (
          <dl className="grid grid-cols-2 gap-x-6 gap-y-3 text-sm sm:grid-cols-3 lg:grid-cols-4">
            <AgentFigure label="Runs" value={String(r.agent.runs)} />
            <AgentFigure
              label="Passed the validator"
              value={percent(r.agent.passRate)}
            />
            <AgentFigure
              label="Valid output format"
              value={percent(r.agent.schemaPassRate)}
            />
            <AgentFigure
              label="Citations valid"
              value={percent(r.agent.citationValidity)}
            />
            <AgentFigure
              label="Amounts and dates faithful"
              value={percent(r.agent.amountFaithfulness)}
            />
            <AgentFigure
              label="Needed a retry"
              value={percent(r.agent.retryRate)}
            />
            <AgentFigure
              label="Average tokens"
              value={r.agent.avgTokens?.toLocaleString("en-NZ") ?? "n/a"}
            />
            <AgentFigure
              label="Average time"
              value={
                r.agent.avgLatencyMs
                  ? `${(r.agent.avgLatencyMs / 1000).toFixed(1)} s`
                  : "n/a"
              }
            />
          </dl>
        ) : (
          <p className="text-muted-foreground text-sm">
            No agent runs have been exported yet. Run the precompute to measure
            the agent.
          </p>
        )}
      </Section>

      <Section title="What these numbers do and do not show">
        <ul className="max-w-prose list-disc space-y-1 pl-5 text-sm">
          {r.limits.map((l) => (
            <li key={l}>{l}</li>
          ))}
          <li>
            The validator checks that citations exist and that figures match the
            cited records. It does not check whether the reasoning is right.
          </li>
        </ul>
      </Section>
    </>
  );
}

function AgentFigure({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="text-muted-foreground">{label}</dt>
      <dd className="num mt-0.5 text-lg font-semibold">{value}</dd>
    </div>
  );
}
